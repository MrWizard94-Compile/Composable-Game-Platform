/**
 * Boundary guest. It copies one simulation proposal and clamps each move.
 * Coordinates are signed 32-bit integers. The inclusive gate is 0 through 1000.
 * A command that is not a move, or a number it cannot read, fails the call.
 * The heap bump resets on every hook. The result sits below the heap, and the
 * host copies it out before the next allocation.
 * The register payload is only `dispatch: true`, so the host mints the handle.
 */

