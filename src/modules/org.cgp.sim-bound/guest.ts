type Needle = { start: number; length: number };

function refuse(error: Needle): number[] {
  return [
    ...o.i32Const(error.start),
    ...o.globalSet(1),
    ...o.i32Const(error.length),
    ...o.globalSet(2),
    ...o.i32Const(1),
    ...o.ret,
  ];
}

function checked(call: number[], error: Needle): number[] {
  return [...call, ...o.if, ...refuse(error), ...o.end];
}

function findCall(ptrLocal: number, lenLocal: number, needle: Needle): number[] {
  return [
    ...o.localGet(ptrLocal),
    ...o.localGet(lenLocal),
    ...o.i32Const(needle.start),
    ...o.i32Const(needle.length),
    ...o.call(0),
  ];
}

