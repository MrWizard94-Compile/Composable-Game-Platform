const encoder = new TextEncoder();

function mark(parts: Array<{ at: number; bytes: Uint8Array }>, text: string, at: { n: number }) {
  const bytes = encoder.encode(text);
  const start = at.n;
  parts.push({ at: start, bytes });
  at.n += bytes.length;
  return { start, length: bytes.length };
}

