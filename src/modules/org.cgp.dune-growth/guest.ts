function fail(at: number, length: number): number[] {
  return [...o.i32Const(at), ...o.globalSet(1), ...o.i32Const(length), ...o.globalSet(2), ...o.i32Const(1), ...o.ret];
}

export function duneGrowthGuest(): Uint8Array {
  const parts: Array<{ at: number; bytes: Uint8Array }> = [];
  const cursor = { n: 256 };
  const rate = mark(parts, "growthRate", cursor);
  const ceiling = mark(parts, "maxStage", cursor);
  const spring = mark(parts, '"spring"', cursor);
  const summer = mark(parts, '"summer"', cursor);
  const autumn = mark(parts, '"autumn"', cursor);
  const winter = mark(parts, '"winter"', cursor);
  const missingRate = mark(parts, "missing rate", cursor);
  const missingCeiling = mark(parts, "missing ceiling", cursor);
  const missingSeason = mark(parts, "missing season", cursor);
  const badStage = mark(parts, "bad stage", cursor);
  const registerJson = JSON.stringify({
    contributions: [
      {
        slotId: "flora.growth-model",
        id: "dune",
        payload: {
          strategyId: "dune",
          label: "Dune growth",
          summary: "Fixed-point seasons. Spring is 1.2 and winter is 0.05.",
          advance: { dispatch: true },
        },
      },
    ],
  });
  const registered = mark(parts, registerJson, cursor);
  if (cursor.n >= FORMAT_AT) throw new Error("Guest constants overlap the format buffer.");

  const findNeedle = (start: number, length: number) => [
    ...o.localGet(1),
    ...o.localGet(2),
    ...o.i32Const(start),
    ...o.i32Const(length),
    ...o.call(0),
  ];

  const readHundredths = (needleLength: number, dest: number, errAt: number, errLen: number) => [
    ...o.localTee(3),
    ...o.i32Const(-1),
    ...o.i32Eq,
    ...o.if,
    ...fail(errAt, errLen),
    ...o.end,
    ...o.localGet(3),
    ...o.i32Const(needleLength),
    ...o.i32Add,
    ...o.localGet(1),
    ...o.localGet(2),
    ...o.i32Add,
    ...o.call(1),
    ...o.localTee(dest),
    ...o.i32Const(-1),
    ...o.i32Eq,
    ...o.if,
    ...fail(errAt, errLen),
    ...o.end,
  ];

  const takeSeason = (start: number, length: number, factor: number) => [
    ...findNeedle(start, length),
    ...o.localTee(3),
    ...o.i32Const(-1),
    ...o.i32Ne,
    ...o.if,
    ...o.i32Const(factor),
    ...o.localSet(6),
    ...o.localGet(3),
    ...o.i32Const(length),
    ...o.i32Add,
    ...o.localGet(1),
    ...o.localGet(2),
    ...o.i32Add,
    ...o.call(1),
    ...o.localSet(7),
    ...o.end,
  ];

  const hook = [
    ...o.localGet(0),
    ...o.i32Eqz,
    ...o.if,
    ...o.i32Const(registered.start),
    ...o.globalSet(1),
    ...o.i32Const(registered.length),
    ...o.globalSet(2),
    ...o.i32Const(0),
    ...o.ret,
    ...o.end,
    ...o.localGet(0),
    ...o.i32Const(5),
    ...o.i32Ne,
    ...o.if,
    ...o.i32Const(0),
    ...o.globalSet(2),
    ...o.i32Const(0),
    ...o.ret,
    ...o.end,
    ...findNeedle(rate.start, rate.length),
    ...readHundredths(rate.length, 4, missingRate.start, missingRate.length),
    ...findNeedle(ceiling.start, ceiling.length),
    ...readHundredths(ceiling.length, 5, missingCeiling.start, missingCeiling.length),
    ...o.i32Const(-1),
    ...o.localSet(7),
    ...takeSeason(spring.start, spring.length, 120),
    ...takeSeason(summer.start, summer.length, 80),
    ...takeSeason(autumn.start, autumn.length, 30),
    ...takeSeason(winter.start, winter.length, 5),
    ...o.localGet(6),
    ...o.i32Eqz,
    ...o.if,
    ...fail(missingSeason.start, missingSeason.length),
    ...o.end,
    ...o.localGet(7),
    ...o.i32Const(-1),
    ...o.i32Eq,
    ...o.if,
    ...fail(badStage.start, badStage.length),
    ...o.end,
    ...o.localGet(4),
    ...o.localGet(6),
    ...o.i32Mul,
    ...o.i32Const(50),
    ...o.i32Add,
    ...o.i32Const(100),
    ...o.i32DivU,
    ...o.localGet(7),
    ...o.i32Add,
    ...o.localSet(8),
    ...o.localGet(8),
    ...o.i32Const(0),
    ...o.i32LtS,
    ...o.if,
    ...o.i32Const(0),
    ...o.localSet(8),
    ...o.end,
    ...o.localGet(8),
    ...o.localGet(5),
    ...o.i32GtS,
    ...o.if,
    ...o.localGet(5),
    ...o.localSet(8),
    ...o.end,
    ...o.localGet(8),
    ...o.i32Const(FORMAT_AT),
    ...o.call(2),
    ...o.globalSet(2),
    ...o.i32Const(FORMAT_AT),
    ...o.globalSet(1),
    ...o.i32Const(0),
  ];

  const support = abiSupportFuncs();
  return compileWasm({
    types: [
      { params: 3, results: 1 },
      { params: 1, results: 1 },
      { params: 0, results: 1 },
      { params: 4, results: 1 },
      { params: 2, results: 1 },
    ],
    funcs: [
      { type: 3, locals: 2, body: findBody() },
      { type: 4, locals: 8, body: parseBody() },
      { type: 4, locals: 6, body: formatBody() },
      support[0]!,
      support[1]!,
      support[2]!,
      { type: 0, locals: 6, body: hook },
    ],
    memory: { min: 1, max: 1 },
    globals: [{ init: BUMP_AT }, { init: 0 }, { init: 0 }],
    exports: abiExports(3),
    data: parts.map((item) => ({ offset: item.at, bytes: item.bytes })),
  });
}
