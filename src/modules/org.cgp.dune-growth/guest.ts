/**
 * Fixed-point growth guest.
 * Hundredths. delta = (growthHundredths * factorHundredths + 50) / 100.
 * Spring 120, summer 80, autumn 30, winter 5.
 * The register payload nests `{ dispatch: true }` so the host returns an ABI handle.
 */

const o = wasmOp;
const FORMAT_AT = 1600;
const BUMP_AT = 2048;

const encoder = new TextEncoder();

function mark(parts: Array<{ at: number; bytes: Uint8Array }>, text: string, at: { n: number }) {
  const bytes = encoder.encode(text);
  const start = at.n;
  parts.push({ at: start, bytes });
  at.n += bytes.length;
  return { start, length: bytes.length };
}

